/** Typical ₹/kg used only when no live Mandi price is available for a crop. */
const FALLBACK_PRICE_RULES: [RegExp, number][] = [
  [/tomato/i, 25],
  [/onion/i, 20],
  [/potato/i, 16],
  [/wheat/i, 24],
  [/paddy|rice/i, 22],
  [/soya/i, 46],
  [/pomegranate/i, 90],
  [/grape/i, 60],
  [/apple/i, 100],
  [/cotton|kapas/i, 70],
  [/chilli/i, 40],
  [/gram|dal|arhar|moong|urd|lentil/i, 65],
  [/garlic|ginger|turmeric|cummin|jeera|cardamom|pepper|clove/i, 90],
  [/mustard|groundnut|sesam|sunflower/i, 55],
];

export function fallbackPricePerKg(name: string): number {
  return FALLBACK_PRICE_RULES.find(([re]) => re.test(name))?.[1] ?? 25;
}

/** Normalises a crop/commodity name for loose matching ("Soyabean" ≈ "Soybean"). */
export function normaliseCropName(name: string): string {
  return name
    .toLowerCase()
    .replace(/\(.*?\)/g, "")
    .replace(/soybean/g, "soyabean")
    .replace(/[^a-z]/g, "");
}
