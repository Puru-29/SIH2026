const DICTS: Record<LangCode, TranslationDict> = {
  en: {},
  hi,
  mr,
  pa,
  gu,
  ur: {},
};

const STORAGE_KEYS = ["selectedLanguage", "agrisense-language"];

export interface I18nContextType {
  lang: LangCode;
  setLang: (code: LangCode) => void;
  t: (keyOrText: string, params?: Record<string, string | number>) => string;
  isRTL: boolean;
  formatNumber: (n: number) => string;
  formatCurrency: (n: number) => string;
}

const I18nContext = createContext<I18nContextType>({
  lang: "en",
  setLang: () => {},
  t: (text, params) => {
    if (!params) return text;
    let out = text;
    for (const [k, v] of Object.entries(params)) {
      out = out.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
    return out;
  },
  isRTL: false,
  formatNumber: (n) => n.toLocaleString("en-IN"),
  formatCurrency: (n) => `₹${n.toLocaleString("en-IN")}`,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  // Read language on mount from localStorage or default to en
  useEffect(() => {
    try {
      let saved: LangCode | null = null;
      for (const k of STORAGE_KEYS) {
        const val = localStorage.getItem(k) as LangCode | null;
        if (val && LANGUAGES.some((l) => l.code === val)) {
          saved = val;
          break;
        }
      }
      if (saved) {
        setLangState(saved);
        applyDocumentLangAndDir(saved);
      }
    } catch {
      // ignore storage access errors
    }
  }, []);

  const applyDocumentLangAndDir = (code: LangCode) => {
    if (typeof document === "undefined") return;
    const meta = LANGUAGES.find((l) => l.code === code);
    const isRTL = meta?.dir === "rtl" || code === "ur";
    document.documentElement.lang = code;
    document.documentElement.dir = isRTL ? "rtl" : "ltr";
    document.documentElement.setAttribute("data-lang", code);
  };

  const setLang = useCallback((code: LangCode) => {
    setLangState(code);
    applyDocumentLangAndDir(code);
    try {
      for (const k of STORAGE_KEYS) {
        localStorage.setItem(k, code);
      }
    } catch {
      // ignore
    }
  }, []);

  const t = useCallback(
    (keyOrText: string, params?: Record<string, string | number>): string => {
      const dict = DICTS[lang] || {};
      let template = dict[keyOrText] ?? keyOrText;

      if (params) {
        for (const [k, v] of Object.entries(params)) {
          template = template.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
        }
      }
      return template;
    },
    [lang]
  );

  const formatNumber = useCallback(
    (n: number) => {
      try {
        return n.toLocaleString("en-IN");
      } catch {
        return String(n);
      }
    },
    []
  );

  const formatCurrency = useCallback(
    (n: number) => {
      try {
        return `₹${n.toLocaleString("en-IN")}`;
      } catch {
        return `₹${n}`;
      }
    },
    []
  );

  const isRTL = useMemo(() => {
    const meta = LANGUAGES.find((l) => l.code === lang);
    return meta?.dir === "rtl" || lang === "ur";
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      setLang,
      t,
      isRTL,
      formatNumber,
      formatCurrency,
    }),
    [lang, setLang, t, isRTL, formatNumber, formatCurrency]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
